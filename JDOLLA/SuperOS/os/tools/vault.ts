// Shared read-only vault scanning for the vault tools (recent_changes, link_check, vault_stats, list_reports).
// Rules, all enforced here so no tool can forget them:
//  - only known top-level folders are looked at (never os/, logs/, .git, .claude ...);
//  - dot entries (.env*, .git ...), links, raw/sessions/ and outputs/_work/ are skipped, and nothing follows a link;
//  - the caller never supplies a path: tools get a department slug that must match depts/<slug>.md;
//  - only names, titles, dates and counts leave this module, never a note body.
// Self-contained on purpose (node + zod only): the tools server starts once per run and must stay light.
import { closeSync, lstatSync, openSync, readFileSync, readSync, readdirSync, realpathSync } from "node:fs";
import path from "node:path";
import { z } from "zod";

/** Folders the vault tools may look at. Everything else (os/, logs/, dot-folders) is never scanned. */
export const TOP_FOLDERS = ["wiki", "raw", "outputs", "depts", "skills", "docs", "reports", "daily", "projects", "proposals", "evals", "inbox"] as const;
const SKIP_DIRS: ReadonlySet<string> = new Set(["raw/sessions", "outputs/_work"]);
export const DEPT_SLUG = /^[a-z][a-z0-9-]{0,39}$/;
export const MAX_SCAN_FILES = 20_000;
export const MAX_READ_BYTES = 512 * 1024;
/** Generated by os/vault: never counted as a note and never checked for links. */
export const GENERATED = new Set(["_index.md", "_master-index.md"]);

export type VaultFile = { rel: string; top: string; size: number; mtimeMs: number };
export type Scan = { files: VaultFile[]; truncated: boolean };

/** The vault's real path, or throws if it is missing. */
export function vaultRoot(vault: string): string {
  if (!vault) throw new Error("no vault");
  return realpathSync(vault);
}

/** Regular files under the known top-level folders, as vault-relative posix paths, sorted. Links and dot entries are skipped. */
export function scanVault(vault: string, tops: readonly string[] = TOP_FOLDERS): Scan {
  const root = vaultRoot(vault);
  const files: VaultFile[] = [];
  let truncated = false;
  for (const top of tops) {
    const start = path.join(root, top);
    let st;
    try { st = lstatSync(start); } catch { continue; }
    if (!st.isDirectory() || st.isSymbolicLink() || realpathSync(start) !== start) continue; // a link in place of a folder is not followed
    const stack = [top];
    while (stack.length) {
      const cur = stack.pop() as string;
      let entries;
      try { entries = readdirSync(path.join(root, cur), { withFileTypes: true }); } catch { continue; }
      for (const e of entries) {
        if (e.name.startsWith(".")) continue; // .env*, .git, .hidden: never
        if (e.isSymbolicLink()) continue;     // never follow a link out of the vault
        const rel = `${cur}/${e.name}`;
        if (e.isDirectory()) { if (!SKIP_DIRS.has(rel)) stack.push(rel); continue; }
        if (!e.isFile()) continue;
        if (files.length >= MAX_SCAN_FILES) { truncated = true; continue; }
        let f;
        try { f = lstatSync(path.join(root, rel)); } catch { continue; }
        if (!f.isFile() || f.isSymbolicLink()) continue;
        files.push({ rel, top, size: f.size, mtimeMs: f.mtimeMs });
      }
    }
  }
  files.sort((a, b) => (a.rel < b.rel ? -1 : a.rel > b.rel ? 1 : 0));
  return { files, truncated };
}

/** Markdown files in the vault root (Home.md, CLAUDE.md): link targets, never scanned for anything else. */
export function rootNotes(vault: string): string[] {
  const root = vaultRoot(vault);
  try {
    return readdirSync(root, { withFileTypes: true }).filter((e) => e.isFile() && !e.name.startsWith(".") && e.name.toLowerCase().endsWith(".md")).map((e) => e.name).sort();
  } catch { return []; }
}

/** The department slugs: one per depts/<slug>.md. */
export function knownDepts(vault: string): string[] {
  const root = vaultRoot(vault);
  try {
    return readdirSync(path.join(root, "depts"), { withFileTypes: true })
      .filter((e) => e.isFile() && !e.isSymbolicLink())
      .map((e) => /^([a-z][a-z0-9-]{0,39})\.md$/.exec(e.name)?.[1])
      .filter((s): s is string => s !== undefined)
      .sort();
  } catch { return []; }
}

/** The first bytes of a regular file as text (frontmatter lives here). Never follows a link. */
export function readHead(vault: string, rel: string, bytes = 8192): string {
  const abs = path.join(vaultRoot(vault), ...rel.split("/"));
  const st = lstatSync(abs);
  if (!st.isFile() || st.isSymbolicLink()) throw new Error("not a regular file");
  const fd = openSync(abs, "r");
  try {
    const buf = Buffer.alloc(bytes);
    return buf.subarray(0, readSync(fd, buf, 0, bytes, 0)).toString("utf8");
  } finally { closeSync(fd); }
}

/** A whole note, up to 512 KB (link_check reads bodies internally; they are never returned). */
export function readBody(vault: string, rel: string): string | null {
  const abs = path.join(vaultRoot(vault), ...rel.split("/"));
  const st = lstatSync(abs);
  if (!st.isFile() || st.isSymbolicLink() || st.size > MAX_READ_BYTES) return null;
  return readFileSync(abs, "utf8");
}

const Front = z.object({
  title: z.string().max(300).optional(),
  type: z.string().max(40).optional(),
  updated: z.string().max(40).optional(),
  sources: z.array(z.string().max(300)).max(100).optional(),
});
export type Front = z.infer<typeof Front>;

/** Title, type, updated and sources from a note's frontmatter. Anything odd gives an empty result. */
export function parseFront(head: string): Front {
  const m = /^---\r?\n([\s\S]*?)\r?\n---[ \t]*(?:\r?\n|$)/.exec(head);
  if (!m?.[1]) return {};
  const raw: Record<string, string | string[]> = {};
  let list: string[] | null = null;
  for (const line of m[1].split(/\r?\n/)) {
    const item = /^\s+-\s+(.{1,300})$/.exec(line);
    if (item?.[1] && list) { list.push(item[1].trim().replace(/^["']|["']$/g, "")); continue; }
    const kv = /^([A-Za-z_]{1,20}):[ \t]*(.{0,300})$/.exec(line);
    list = null;
    if (!kv?.[1]) continue;
    const key = kv[1].toLowerCase();
    const value = (kv[2] ?? "").trim();
    if (key === "sources" && !value) { list = []; raw["sources"] = list; continue; }
    if (key === "sources" && value.startsWith("[")) { // inline list: sources: ["a", "b"]
      raw["sources"] = value.replace(/^\[|\]$/g, "").split(",").map((s) => s.trim().replace(/^["']|["']$/g, "")).filter(Boolean);
      continue;
    }
    raw[key] = value.replace(/^["']|["']$/g, "");
  }
  const parsed = Front.safeParse(raw);
  return parsed.success ? parsed.data : {};
}

/** One plain line of copied text: no control characters and no markup that could pass for a link or tag. */
export function clean(text: string, max = 120): string {
  const t = text.replace(/[\p{Cc}\p{Cf}\p{Zl}\p{Zp}]+/gu, " ").replace(/<[^>]*>/g, " ").replace(/\[\[|\]\]/g, "").replace(/[<>`|]/g, "").replace(/\s+/g, " ").trim();
  return t.length > max ? `${t.slice(0, max - 1)}…` : t;
}

/** YYYY-MM-DD of an instant in a time zone. */
export function localDate(ms: number, tz: string): string {
  return new Intl.DateTimeFormat("en-CA", { timeZone: tz, year: "numeric", month: "2-digit", day: "2-digit" }).format(new Date(ms));
}

/** The date `back` days before `date` (both YYYY-MM-DD), by calendar arithmetic, so daylight saving cannot shift it. */
export function dateMinus(date: string, back: number): string {
  const [y, m, d] = date.split("-").map(Number) as [number, number, number];
  return new Date(Date.UTC(y, m - 1, d - back)).toISOString().slice(0, 10);
}

/** Whole days from `from` to `to` (both YYYY-MM-DD). */
export function daysBetween(from: string, to: string): number {
  const f = from.split("-").map(Number) as [number, number, number];
  const t = to.split("-").map(Number) as [number, number, number];
  return Math.round((Date.UTC(t[0], t[1] - 1, t[2]) - Date.UTC(f[0], f[1] - 1, f[2])) / 86_400_000);
}

export const DateOnly = /^\d{4}-\d{2}-\d{2}$/;

/** Output files carry their department in the name: YYYY-MM-DD_<dept>_<slug>.<ext>. */
export function outputDept(name: string): string | null {
  return /^\d{4}-\d{2}-\d{2}_([a-z][a-z0-9-]{0,39})_/.exec(name)?.[1] ?? null;
}

/** The `dept` argument shared by the tools: a slug that must match a real depts/<slug>.md, or an error message. */
export const DeptArg = z.string().regex(DEPT_SLUG).optional();
export function checkDept(vault: string, dept: string | undefined): { ok: true } | { ok: false; error: string } {
  if (dept === undefined) return { ok: true };
  const known = knownDepts(vault);
  return known.includes(dept) ? { ok: true } : { ok: false, error: `Unknown department "${dept}". Known: ${known.join(", ") || "none"}.` };
}
