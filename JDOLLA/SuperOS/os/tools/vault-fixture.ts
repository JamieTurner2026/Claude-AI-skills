export function put(vault: string, rel: string, text: string, mtime?: string): string {
  const f = path.join(vault, rel);
  mkdirSync(path.dirname(f), { recursive: true });
  writeFileSync(f, text);
  if (mtime) { const d = new Date(mtime); utimesSync(f, d, d); }
  return f;
}
