// POST /api/vault/rebuild: same session, origin and header rules as every other write, and a failure never stops the bridge.
import { test, before, after } from "node:test";
import assert from "node:assert/strict";
import { existsSync, mkdtempSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import type { AddressInfo } from "node:net";
import { createBridge } from "../bridge/server.ts";
import type { Bridge } from "../bridge/server.ts";
import { makeGenVault, NOW, TODAY } from "./fixture.ts";

let bridge: Bridge, base: string, vault: string, token: string, logs: string;
let boom = false;

before(async () => {
  const g = makeGenVault();
  vault = g.vault;
  logs = mkdtempSync(path.join(tmpdir(), "vault-route-logs-"));
  bridge = createBridge(g.paths.os, { logDir: logs, now: () => { if (boom) throw new Error("clock exploded"); return NOW; } });
  await new Promise<void>((r) => bridge.server.listen(0, "127.0.0.1", r));
  base = `http://127.0.0.1:${(bridge.server.address() as AddressInfo).port}`;
  token = bridge.mint();
});
after(() => { bridge.server.close(); });

const rebuild = (headers: Record<string, string>) => fetch(`${base}/api/vault/rebuild`, { method: "POST", headers: { "content-type": "application/json", ...headers }, body: "{}" });
const good = () => ({ authorization: `Bearer ${token}`, "x-superos": "1" });

test("the route needs a session, our header and our origin; nothing is written until they are all there", async () => {
  assert.equal((await rebuild({ "x-superos": "1" })).status, 401, "no session");
  assert.equal((await rebuild({ authorization: "Bearer not-a-real-token", "x-superos": "1" })).status, 401, "bad session");
  assert.equal((await rebuild({ authorization: `Bearer ${token}` })).status, 403, "missing x-superos header");
  assert.equal((await rebuild({ ...good(), origin: "http://evil.example" })).status, 403, "wrong origin");
  assert.equal(existsSync(path.join(vault, "wiki/_master-index.md")), false, "none of the refused calls built anything");
  // control: the same call with everything right works
  const ok = await rebuild({ ...good(), origin: base });
  assert.equal(ok.status, 200);
  const body = (await ok.json()) as { date: string; counts: { create: number; skipped: number }; files: { path: string; action: string }[] };
  assert.equal(body.date, TODAY);
  assert.ok(body.counts.create >= 4);
  assert.equal(existsSync(path.join(vault, "wiki/_master-index.md")), true);
  assert.equal(readFileSync(path.join(vault, `daily/${TODAY}.md`), "utf8").split("\n")[0], "<!-- generated by os/vault: do not hand-edit -->");
});

test("asking again changes nothing, and GET is not a way to rebuild", async () => {
  const again = await rebuild(good());
  const body = (await again.json()) as { counts: { create: number; update: number } };
  assert.equal(again.status, 200);
  assert.equal(body.counts.create + body.counts.update, 0);
  const get = await fetch(`${base}/api/vault/rebuild`, { headers: { authorization: `Bearer ${token}` } });
  assert.ok([404, 405].includes(get.status), `GET gave ${get.status}`);
});

test("a failed rebuild is logged to router.jsonl, answers 500, and the bridge keeps serving", async () => {
  boom = true;
  const res = await rebuild(good());
  boom = false;
  assert.equal(res.status, 500);
  assert.equal((await fetch(`${base}/api/state`, { headers: { authorization: `Bearer ${token}` } })).status, 200, "still serving");
  const lines = readFileSync(path.join(logs, "router.jsonl"), "utf8").trim().split("\n").map((l) => JSON.parse(l) as Record<string, unknown>);
  const failed = lines.find((l) => l["event"] === "vault-build-failed");
  assert.equal(failed?.["trigger"], "api");
  assert.match(String(failed?.["error"]), /clock exploded/);
  assert.ok(lines.some((l) => l["event"] === "vault-build" && l["trigger"] === "api"), "successful builds are logged too");
  // control: it works again afterwards
  assert.equal((await rebuild(good())).status, 200);
});

test("vault.rebuild() never throws, even when the build does", () => {
  boom = true;
  assert.doesNotThrow(() => assert.equal(bridge.vault.rebuild("start"), null));
  boom = false;
  assert.ok(bridge.vault.rebuild("start"));
});

test("createBridge alone does not write into the vault (the clock is started by `npm start`)", async () => {
  const g = makeGenVault();
  const b = createBridge(g.paths.os, { logDir: mkdtempSync(path.join(tmpdir(), "vault-route-logs-")) });
  await new Promise<void>((r) => b.server.listen(0, "127.0.0.1", r));
  assert.equal(existsSync(path.join(g.vault, "wiki/_master-index.md")), false);
  b.server.close();
});
